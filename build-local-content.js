// Generates the file:// fallback bundle from the editable JSON content files.
const fs=require('node:fs');
const path=require('node:path');
const names=['maps','orbs','towers','achievements','tutorial','waves','difficulties'];
const content=Object.fromEntries(names.map(name=>[name,JSON.parse(fs.readFileSync(path.join(__dirname,'data',`${name}.json`),'utf8'))]));
const output=`/* Generated by build-local-content.js. Do not edit directly. */\n(function(root){root.ElephantTrackDefenseLocalContent=${JSON.stringify(content)};})(globalThis);\n`;
fs.writeFileSync(path.join(__dirname,'content-local.js'),output);
console.log('Generated content-local.js for direct file launches.');
