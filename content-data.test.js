const assert=require('node:assert/strict');
const fs=require('node:fs');
const content=require('./test-content.js');
const schema=require('./content-schema.js');
assert.equal(content.activeMap.id,'map_foundry_sector_07');
assert.equal(content.maps.maps.length,2);
assert.equal(content.indexes.maps.frozen_expanse.totalWaves,20);
assert.equal(content.indexes.maps.frozen_expanse.trackWaypoints.length,26);
assert.equal(content.indexes.maps.frozen_expanse.puddleEffects.snowMultiplier,.9);
assert.equal(content.indexes.maps.frozen_expanse.puddleEffects.iceMultiplier,1.15);
assert.equal(content.indexes.maps.frozen_expanse.puddleEffects.infoText,'Snow puddles slow orbs by 10%. Ice puddles speed up orbs by 15%.');
assert.equal(content.indexes.waveSets.frozen_waves.waveIds.length,20);
assert.equal(content.indexes.waves.frozen_wave_20.orbCount,32);
assert.equal(content.activeMap.trackWaypoints.length,22);
assert.equal(content.orbs.normalTiers.length,11);
assert.equal(content.towers.towers.length,9);
assert.equal(content.achievements.achievements.length,11);
assert.equal(content.tutorial.steps.length,23);
assert.equal(content.waves.waves.length,50);
assert.deepEqual(content.waves.finales[0].encounterOrder.slice(-2),['tier_10','fused_prismatic_boss']);
assert.equal(content.indexes.orbs.fused_prismatic_boss.maxHp,10000);
assert.deepEqual(content.difficulties.difficulties.map(item=>item.id),['easy','normal','hard']);
assert.equal(content.indexes.difficulties.hard.elephantFinalDamageMultiplier,.93);
const raw=Object.fromEntries(['maps','orbs','towers','achievements','tutorial','waves','difficulties'].map(name=>[name,JSON.parse(fs.readFileSync(`data/${name}.json`,'utf8'))]));
raw.maps.defaultMapId='frozen_expanse';
const frozenContent=schema.build(raw);
assert.equal(frozenContent.config.TOTAL_WAVES,20);
assert.equal(frozenContent.config.WORLD_HEIGHT,1780);
assert.equal(frozenContent.activeWaveSet.id,'frozen_waves');
assert.equal(frozenContent.wavesByNumber[20].id,'frozen_wave_20');
const gameplay=fs.readFileSync('./game.js','utf8');
const mapSystem=fs.readFileSync('./map-system.js','utf8');
assert.doesNotMatch(gameplay,/const CONFIG\s*=\s*Object\.freeze\(\{/);
assert.doesNotMatch(gameplay,/const TUTORIAL_STEPS\s*=\s*\[/);
assert.doesNotMatch(gameplay,/const ACHIEVEMENTS\s*=\s*Object\.freeze\(\[/);
assert.throws(()=>require('./content-schema.js').build({...content,maps:{...content.maps,defaultMapId:'missing_map'}}),/defaultMapId references missing map/);
assert.match(mapSystem,/OWNER_MAP_LAUNCH_KEY/);
assert.match(mapSystem,/verb==='\/win'/);
assert.match(mapSystem,/Map selection opened\./);
assert.match(mapSystem,/verb==='\/map'/);
assert.match(mapSystem,/Usage: \/map <foundry\|ice>/);
assert.match(mapSystem,/Unknown map\. Use: foundry or ice\./);
assert.match(mapSystem,/mapAliases=\{foundry:'map_foundry_sector_07',ice:'frozen_expanse'\}/);
assert.match(mapSystem,/ownerMapChooserOpen/);
assert.match(mapSystem,/puddleOrbSpeedBase=orbMovementSpeed/);
assert.match(mapSystem,/orb\.frozenPuddleType=puddle\?\.type\|\|null/);
assert.match(mapSystem,/puddleRules\.snowMultiplier/);
assert.match(mapSystem,/puddleRules\.iceMultiplier/);
assert.match(mapSystem,/validateFrozenPuddleLayout/);
assert.match(mapSystem,/drawOrbPuddleFeedback/);
assert.match(gameplay,/FROZEN_TRACK_PUDDLES/);
assert.match(gameplay,/puddleBlobPath/);
assert.match(gameplay,/drawBlobTexture/);
assert.match(gameplay,/drawFrozenTrack\(theme\)/);
assert.match(gameplay,/prefersReducedMotion\(\)/);
console.log('Content JSON validation tests passed.');
